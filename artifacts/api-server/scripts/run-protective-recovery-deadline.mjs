import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { createServer } from "node:net";
import { fileURLToPath } from "node:url";

const api = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const unitTests = [
  "protectiveRecoveryDeadline.test.ts",
  "ownerFeeEmergencyExitAuthenticatedRecovery.test.ts",
  "ownerFeeEmergencyExitReconciliationCommit.test.ts",
  "ownerFeeEmergencyExitRestartRecovery.test.ts",
  "ownerFeeEmergencyExitSignedDispatch.test.ts",
];

// The only PostgreSQL destination is generated by this runner for its own new
// cluster. There is no ambient URL, credential, service, or shared-DB fallback.
export function disposableTarget(port, stamp) {
  if (!Number.isInteger(port) || port < 1 || port > 65535 || !Number.isSafeInteger(stamp) || stamp < 1)
    throw Error("invalid_disposable_target");
  return `postgresql://v13_test@127.0.0.1:${port}/protective_deadline_disposable_${stamp}`;
}

export function childEnvironment({ path, home, apiDirectory, fence, target }) {
  return {
    PATH: path, HOME: home, NODE_ENV: "test", TZ: "UTC", PGTZ: "UTC",
    DATABASE_URL: target ?? "postgresql://offline:offline@127.0.0.1:1/offline",
    ...(target ? { V13_PROTECTIVE_DEADLINE_DISPOSABLE_URL: target } : {}),
    NODE_PATH: join(apiDirectory, "node_modules"),
    NODE_OPTIONS: `--require=${JSON.stringify(fence)}`,
    PGOPTIONS: "-c statement_timeout=10000 -c lock_timeout=5000",
  };
}

export function networkFence(port = null) {
  if (port !== null && (!Number.isInteger(port) || port < 1 || port > 65535))
    throw Error("invalid_disposable_port");
  return `
const net = require("node:net"), original = net.Socket.prototype.connect;
let denied = 0;
const reject = () => { denied++; throw Error("protective_recovery_network_forbidden"); };
net.Socket.prototype.connect = function(...args) {
  let o = args[0]; if (Array.isArray(o)) o = o[0];
  const host = o && typeof o === "object" ? o.host || o.hostname : args[1];
  const port = Number(o && typeof o === "object" ? o.port : o);
  if (${JSON.stringify(port)} === null || host !== "127.0.0.1" || port !== ${JSON.stringify(port)}) reject();
  return original.apply(this, args);
};
globalThis.fetch = reject;
process.on("exit", () => {
  console.log("PROTECTIVE_RECOVERY_NETWORK_FENCE", { denied });
  if (denied) process.exitCode = 1;
});
`;
}

export function postgresBinaries(path, exists = existsSync) {
  const directories = [...(path ?? "").split(delimiter).filter(Boolean),
    "/usr/lib/postgresql/16/bin", "/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/15/bin"];
  const extension = process.platform === "win32" ? ".exe" : "";
  const directory = directories.find(dir => ["initdb", "pg_ctl", "createdb"].every(name => exists(join(dir, name + extension))));
  if (!directory) throw Error("PostgreSQL binaries required; no connected-database fallback exists");
  return Object.fromEntries(["initdb", "pg_ctl", "createdb"].map(name => [name, join(directory, name + extension)]));
}

// Dependency injection permits cleanup verification without launching a server.
export function withDisposableCluster({ root, binaries, port, database, run, test, remove }) {
  let startAttempted = false;
  try {
    run(binaries.initdb, ["-D", join(root, "data"), "-U", "v13_test", "--auth=trust", "--no-locale",
      "--encoding=UTF8", "--no-sync", "--set=shared_buffers=16MB"]);
    startAttempted = true;
    run(binaries.pg_ctl, ["-D", join(root, "data"), "-l", join(root, "postgres.log"), "-o",
      `-h 127.0.0.1 -p ${port} -c unix_socket_directories=''`, "-w", "start"]);
    run(binaries.createdb, ["-h", "127.0.0.1", "-p", String(port), "-U", "v13_test", database]);
    test();
  } finally {
    // A failed start may still have started a backend. Require a successful stop
    // before deleting the directory; an uncertain cleanup stays visible.
    if (startAttempted) run(binaries.pg_ctl, ["-D", join(root, "data"), "-m", "immediate", "-w", "stop"]);
    remove();
  }
}

export async function main(args = process.argv.slice(2)) {
  if (args.length > 1 || (args.length === 1 && args[0] !== "--postgres"))
    throw Error("usage: run-protective-recovery-deadline.mjs [--postgres]");
  const postgres = args[0] === "--postgres";
  const binaries = postgres ? postgresBinaries(process.env.PATH) : null;
  let port = null;
  if (postgres) {
    const server = createServer();
    await new Promise((yes, no) => { server.once("error", no); server.listen(0, "127.0.0.1", yes); });
    port = server.address().port;
    await new Promise(yes => server.close(yes));
  }
  const root = mkdtempSync(join(tmpdir(), "protective-recovery-deadline-"));
  const target = postgres ? disposableTarget(port, Date.now()) : undefined;
  const fence = join(root, "network-fence.cjs");
  writeFileSync(fence, networkFence(port));
  const env = childEnvironment({ path: process.env.PATH, home: process.env.HOME, apiDirectory: api, fence, target });
  const run = (command, commandArgs) => {
    const result = spawnSync(command, commandArgs, { cwd: api, env, stdio: "inherit", timeout: 180_000 });
    if (result.error || result.status !== 0)
      throw Error(`Protective recovery command failed: ${command}, status=${result.status}`, { cause: result.error });
  };
  const test = () => {
    const names = postgres ? ["protectiveRecoveryDeadline.postgres.test.ts"] : unitTests;
    const files = names.map(name => `src/lib/strata/${name}`);
    const esbuild = join(api, "node_modules/esbuild/bin/esbuild");
    run(process.execPath, [esbuild, ...files, "--bundle", "--platform=node", "--format=cjs",
      `--outdir=${root}`, "--out-extension:.js=.cjs", "--external:pg-native", "--external:pdfjs-dist",
      "--external:pino", "--external:pino-pretty"]);
    run(process.execPath, ["--test", ...names.map(name => join(root, name.replace(/\.ts$/, ".cjs")))]);
  };
  const remove = () => rmSync(root, { recursive: true, force: true });
  if (postgres) {
    withDisposableCluster({ root, binaries, port, database: new URL(target).pathname.slice(1), run, test, remove });
  } else {
    try { test(); } finally { remove(); }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error); process.exitCode = 1; });
}
